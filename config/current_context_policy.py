def domain_vocabulary(domain: str) -> DomainVocabulary:
    key = str(domain or "").strip().lower()
    if key not in DOMAIN_VOCABULARY:
        raise KeyError(f"Unknown Current Context domain: {domain!r}")
    return DOMAIN_VOCABULARY[key]


def domain_relevance_terms(domain: str) -> tuple[str, ...]:
    return domain_vocabulary(domain).relevance_terms


